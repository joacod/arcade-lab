import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('./', import.meta.url);
const source = name => fileURLToPath(new URL(`source/${name}.png`, root));
const target = name => fileURLToPath(new URL(name, root));
const dimensions = {};
const roomNames = ['hall', 'gallery', 'library', 'kitchen', 'bell'];
// Source seams and wall/floor edges inspected in the complete six-room painting.
const rows = [0, 306, 611, 916], columns = [0, 859, 1717];
const floorEdges = [254, 254, 540, 532, 854];
for (const [i, name] of roomNames.entries()) {
  const row = Math.floor(i / 2), col = i % 2;
  const left = columns[col], top = rows[row], width = columns[col + 1] - left;
  const wall = floorEdges[i];
  const upper = await sharp(source('rooms')).extract({ left, top, width, height: wall - top }).resize(1440, 548).toBuffer();
  const lower = await sharp(source('rooms')).extract({ left, top: wall, width, height: rows[row + 1] - wall }).resize(1440, 262).toBuffer();
  await sharp({ create: { width: 1440, height: 810, channels: 3, background: '#101a21' } })
    .composite([{ input: upper, left: 0, top: 0 }, { input: lower, left: 0, top: 548 }])
    .webp({ quality: 92 }).toFile(target(`${name}.webp`));
  dimensions[name] = [1440, 810];
}
for (const name of ['cast', 'walk', 'props', 'equipment', 'service']) {
  const info = await sharp(source(name)).metadata();
  dimensions[name] = [info.width, info.height];
  await sharp(source(name)).webp({ quality: 94, alphaQuality: 100 }).toFile(target(`${name}.webp`));
}

async function frames(sheet, columns, rows, names) {
  const { data, info } = await sharp(source(sheet)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  return Object.fromEntries(names.map((name, i) => {
    const col = i % columns, row = Math.floor(i / columns);
    const x0 = Math.round(col * info.width / columns), y0 = Math.round(row * info.height / rows);
    const x1 = Math.round((col + 1) * info.width / columns), y1 = Math.round((row + 1) * info.height / rows);
    let left = x1, top = y1, right = x0, bottom = y0;
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
      if (data[(y * info.width + x) * 4 + 3] > 32) {
        left = Math.min(left, x); top = Math.min(top, y); right = Math.max(right, x); bottom = Math.max(bottom, y);
      }
    }
    if (left > right) throw new Error(`Empty drawing: ${name}`);
    left = Math.max(x0, left - 2); top = Math.max(y0, top - 2);
    right = Math.min(x1 - 1, right + 2); bottom = Math.min(y1 - 1, bottom + 2);
    return [name, { x: left, y: top, w: right - left + 1, h: bottom - top + 1 }];
  }));
}
const propFrames = await frames('props', 5, 5, ['door', 'crate', 'portraitScream', 'portraitQuiet', 'emptyFrame',
  'inhabitedFrame', 'journal', 'musicBox', 'photo', 'brush', 'poker', 'tubeClosed', 'tubeOpen', 'cabinetClosed', 'cabinetOpen',
  'chainLoose', 'chainAttached', 'mirrorOut', 'mirrorIn', 'housing', 'whisper', 'lantern', 'bellows', 'fork', 'keys']);
const equipmentFrames = await frames('equipment', 3, 3, ['lens', 'chalk', 'longBrush', 'cabinetKey', 'windingKey', 'casebook', 'table', 'brush', 'satchel']);
const cast = await frames('cast', 4, 2, ['idle', 'reach', 'lantern', 'evelyn', 'vale', 'oswald', 'brindle', 'guest']);
const walk = await frames('walk', 4, 2, ['walkA', 'walkB', 'walkC', 'walkD', 'walkE', 'walkF', 'walkG', 'walkH']);
const castFrames = {};
// Explicit pelvis columns and foot baselines preserve pose height and gait bob.
const castRegistration = [[234, 434], [602, 434], [1080, 434], [1545, 434], [244, 881], [668, 881], [1100, 881], [1520, 881]];
for (const [i, [name, frame]] of Object.entries(cast).entries()) {
  const [hip, foot] = castRegistration[i];
  castFrames[name] = { ...frame, sheet: 'cast', scale: name === 'reach' || name === 'lantern' || name === 'idle' ? 317 / 434 : 317 / frame.h,
    anchorX: hip - frame.x, foot: foot - frame.y };
}
const walkHips = [232, 676, 1119, 1563, 232, 676, 1119, 1563];
for (const [i, [name, frame]] of Object.entries(walk).entries()) {
  castFrames[name] = { ...frame, sheet: 'walk', scale: 317 / 434, anchorX: walkHips[i] - frame.x,
    foot: (i < 4 ? 432 : 875) - frame.y };
}
await writeFile(target('frames.ts'), '// Generated by art/deluxe/pack.mjs. Complete authored drawings, never assembled parts.\n'
  + Object.entries({ dimensions, propFrames, equipmentFrames, castFrames }).map(([name, value]) =>
    `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`).join('\n'));
