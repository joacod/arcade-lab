import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('./', import.meta.url);
const source = name => fileURLToPath(new URL(`source/${name}.png`, root));
const rooms = ['hall', 'gallery', 'library', 'kitchen', 'bell'];
// Inspected seams of the six-plate source. The unused sixth painting is retained
// in the editable source, not in the runtime bundle.
for (const [i, name] of rooms.entries()) {
  const left = i % 2 * 683, top = [0, 383, 767][Math.floor(i / 2)];
  const wall = [296, 310, 298, 302, 311][i], height = i < 4 ? 383 : 384;
  // Register the painted floor edge to the existing 365-unit navigation floor.
  const upper = await sharp(source('rooms')).extract({ left, top, width: 683, height: wall }).resize(960, 365).toBuffer();
  const lower = await sharp(source('rooms')).extract({ left, top: top + wall, width: 683, height: height - wall }).resize(960, 175).toBuffer();
  await sharp({ create: { width: 960, height: 540, channels: 3, background: '#101a21' } })
    .composite([{ input: upper, left: 0, top: 0 }, { input: lower, left: 0, top: 365 }])
    .webp({ quality: 90 }).toFile(fileURLToPath(new URL(`${name}.webp`, root)));
}
for (const name of ['cast', 'walk', 'props', 'equipment', 'service']) {
  await sharp(source(name)).webp({ quality: 93, alphaQuality: 100 }).toFile(fileURLToPath(new URL(`${name}.webp`, root)));
}
await exportFrames('props', 5, 'propFrames', ['door', 'crate', 'portraitScream', 'portraitQuiet', 'emptyFrame',
  'inhabitedFrame', 'journal', 'musicBox', 'photo', 'brush',
  'poker', 'tubeClosed', 'tubeOpen', 'cabinetClosed', 'cabinetOpen',
  'chainLoose', 'chainAttached', 'mirrorOut', 'mirrorIn', 'housing',
  'whisper', 'lantern', 'bellows', 'fork', 'keys']);
await exportFrames('equipment', 3, 'equipmentFrames', ['lens', 'chalk', 'longBrush',
  'cabinetKey', 'windingKey', 'casebook', 'table', 'brush', 'satchel']);
async function exportFrames(sheet, columns, variable, names) {
const { data, info } = await sharp(source(sheet)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const frames = {};
for (const [i, name] of names.entries()) {
  const col = i % columns, row = Math.floor(i / columns);
  const x0 = Math.round(col * info.width / columns), y0 = Math.round(row * info.height / columns);
  const x1 = Math.round((col + 1) * info.width / columns), y1 = Math.round((row + 1) * info.height / columns);
  let left = x1, top = y1, right = x0, bottom = y0;
  for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
    if (data[(y * info.width + x) * 4 + 3] > 32) {
      left = Math.min(left, x); top = Math.min(top, y);
      right = Math.max(right, x); bottom = Math.max(bottom, y);
    }
  }
  left = Math.max(x0, left - 3); top = Math.max(y0, top - 3);
  right = Math.min(x1 - 1, right + 3); bottom = Math.min(y1 - 1, bottom + 3);
  frames[name] = { x: left, y: top, w: right - left + 1, h: bottom - top + 1 };
}
await writeFile(new URL(sheet === 'props' ? 'prop-frames.ts' : 'equipment-frames.ts', root),
  '// Generated by art/pack.mjs from the alpha bounds of whole object drawings.\nexport const ' + variable + ' = '
  + JSON.stringify(frames, null, 2) + ' as const;\n');
}
